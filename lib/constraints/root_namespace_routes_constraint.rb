module Constraints
  class RootNamespaceRoutesConstraint
    TOP_LEVEL_ROUTES = %w[
      -
      .well-known
      404.html
      422.html
      500.html
      502.html
      503.html
      admin
      api
      apple-touch-icon.png
      assets
      dashboard
      articles
      attachments
      settings
      about-nameem
      policy
      explore
      favicon.ico
      favicon.png
      files
      groups
      health_check
      up
      help
      import
      jwt
      login
      oauth
      profile
      projects
      public
      robots.txt
      signup
      search
      sitemap
      sitemap.xml
      sitemap.xml.gz
      uploads
      users
      latest_feed
      popular_feed
      featured_feed
      picked_feed
      user_articles
      feed
      new-story
      auth
      callback
      callback_login
      callback_create
      publish_modal
      static_pages
      home
      sessions
      registrations
      callbacks
      rails
      rails_health_check
      root
    ].freeze

    def matches?(request)
      request.path_parameters[:slug].present? && TOP_LEVEL_ROUTES.exclude?(request.path_parameters[:slug])
    end
  end
end
